declare(strict_types=1);

function bg_mod_supported_languages(): array
{
    return ['en', 'bg'];
}

function bg_mod_resolve_language(): string
{
    $sessionKey = 'bg_mod_ui_lang';
    $requested = strtolower(trim((string) ($_GET['lang'] ?? $_POST['lang'] ?? '')));
    $supported = bg_mod_supported_languages();

    if (in_array($requested, $supported, true)) {
        $_SESSION[$sessionKey] = $requested;
        return $requested;
    }

    $stored = strtolower(trim((string) ($_SESSION[$sessionKey] ?? '')));

    if (in_array($stored, $supported, true)) {
        return $stored;
    }

    $_SESSION[$sessionKey] = 'en';
    return 'en';
}

function bg_mod_current_language(): string
{
    return bg_mod_resolve_language();
}

