    ];

    if (str_starts_with($normalized, 'Direct ban was sent successfully. Internal reference: ')) {
        $reference = trim(substr($normalized, strlen('Direct ban was sent successfully. Internal reference: ')), '. ');
        return bg_mod_t('msg.direct_ban_sent', ['reference' => $reference], $lang);
    }

    if (str_starts_with($normalized, 'Direct unban completed. Internal record ')) {
        $reference = trim(substr($normalized, strlen('Direct unban completed. Internal record ')));
        $reference = preg_replace('/\s+was updated\.$/', '', (string) $reference) ?? $reference;
