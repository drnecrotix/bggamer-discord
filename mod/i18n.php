function bg_mod_localize_message_payload(mixed $payload, ?string $lang = null): mixed
{
    if (!is_array($payload) || !isset($payload['message'])) {
        return $payload;
    }

    $payload['message'] = bg_mod_translate_runtime_message((string) $payload['message'], $lang);
    return $payload;
}

